/**
 * Regenerates src/lib/schema-sql.ts from prisma/schema.prisma.
 * The output is embedded in the app so /api/setup can bootstrap a fresh
 * remote Turso/libSQL database without needing the Prisma CLI at runtime.
 *
 * Run after ANY schema change:  bun run db:schema-dump
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const res = spawnSync(
  "bunx",
  [
    "prisma",
    "migrate",
    "diff",
    "--from-empty",
    "--to-schema-datamodel",
    "prisma/schema.prisma",
    "--script",
  ],
  { encoding: "utf8" },
);

if (res.status !== 0 || !res.stdout.trim()) {
  console.error("✗ prisma migrate diff failed:", res.stderr);
  process.exit(1);
}

const sql = res.stdout.trim();

if (/[`$\\]/.test(sql)) {
  console.error("✗ Generated SQL contains characters unsafe for embedding; aborting.");
  process.exit(1);
}

const out =
  "// AUTO-GENERATED by scripts/gen-schema.ts — do not edit by hand.\n" +
  "// Regenerate with: bun run db:schema-dump\n\n" +
  "export const SCHEMA_SQL = `" +
  sql +
  "`;\n";

writeFileSync("src/lib/schema-sql.ts", out);
console.log(
  `✓ src/lib/schema-sql.ts updated (${sql.split("\n").length} lines)`,
);
